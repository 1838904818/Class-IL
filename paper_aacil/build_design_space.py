"""Render the published design-space evidence without training or re-exporting runs."""
import hashlib
import json
from pathlib import Path
from statistics import mean, stdev

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / 'paper_aacil/results'


def read(path):
    return json.loads(path.read_text(encoding='utf-8'))


def trajectory(r):
    cps = r['checkpoints']
    tasks = r.get('tasks', r['identity'].get('tasks'))
    recalls = []
    for index, cp in enumerate(cps):
        source = cp if 'operating_points' in cp else r['calibrated_stages'][index]
        assert source['task_index'] == cp['task_index']
        cm = source['operating_points']['0.01']['confusion_matrix']
        recalls.append({c: cm[c][c] / sum(cm[c]) for c in cp['seen_classes']})
    old = [c for task in tasks[:-1] for c in task]
    forgetting = mean(max(x[c] for x in recalls[:-1] if c in x) - recalls[-1][c] for c in old)
    return mean(mean(x.values()) for x in recalls), mean(recalls[-1].values()), forgetting


def pm(values):
    return f'{100*mean(values):.1f} $\\pm$ {100*stdev(values):.1f}'


def build():
    selection = read(RESULTS / 'section138_selection.json')
    assert len(selection['rows']) == 48
    for name, digest in selection['screening_sha256'].items():
        assert hashlib.sha256((RESULTS / 'section138_screen' / name).read_bytes()).hexdigest() == digest
    out = [r'% Generated by paper_aacil/build_design_space.py from published JSON only.',
           r'\begin{table*}[p]\centering\scriptsize',
           r'\caption{Design-space study; no configuration met the pre-registered K1. Screening seeds 1--2 only. Values are percentages (forgetting in percentage points). Score averages both final decision views over both datasets and seeds. D: default final balanced accuracy; L: final balanced accuracy at a 1\% calibration FPR target; F: signed old-class forgetting in the latter view, including Normal. * denotes selected configurations; R denotes the reference. These screening means are not confirmation evidence.}',
           r'\label{tab:design-space-screen}', r'\begin{tabular}{lrrrrrrr}\toprule',
           r'Configuration & Score & UNSW D & UNSW L & UNSW F & CIC D & CIC L & CIC F \\\midrule']
    for row in selection['rows']:
        name = row['configuration'].replace('S138-', '')
        name += '*' if row['configuration'] in selection['selected'] else (' R' if row['reference'] else '')
        values = [row['score']]
        for dataset in ('UNSW-NB15', 'CIC-IDS-2017'):
            cells = [c for c in row['cells'] if c['dataset'] == dataset]
            assert {c['seed'] for c in cells} == {1, 2}
            values.extend(mean(c[k] for c in cells) for k in ('default_bacc', 'fpr01_bacc', 'forgetting'))
        out.append(name + ' & ' + ' & '.join(f'{100*v:.2f}' for v in values) + r' \\')
    out += [r'\bottomrule\end{tabular}\end{table*}',
            r'\begin{table*}[p]\centering\scriptsize',
            r'\caption{Confirmation-stage descriptive results, seeds 10--14, mean $\pm$ sample standard deviation. All columns use the 1\% calibration FPR target, not default decisions or guaranteed test FPR. All three selected configurations failed K1 on both datasets. K2 passing means no significant worsening under the original test; it does not establish equivalence or non-inferiority. K3 passed under the original criterion. No configuration was confirmed.}',
            r'\label{tab:design-space-confirm}',r'\begin{tabular}{llrrr}\toprule',
            r'Dataset & Configuration & Mean incremental BAcc & Final BAcc & Signed forgetting \\\midrule']
    for dataset in ('unsw-nb15', 'cic-ids-2017'):
        methods = [(m, RESULTS / 'section147_confirmation' / dataset) for m in selection['selected']]
        methods += [(m, RESULTS / 'section123_confirmation' / dataset) for m in ('ar', 'ar_joint', 'replay_bs', 'freq', 'wacb')]
        methods += [('er_bal_tabt', None)]
        for method, directory in methods:
            rows = []
            for seed in range(10, 15):
                path = directory / f'{method}_seed{seed}.json' if directory else ROOT / f'ncd/results/problem_scout/section123/publication_v1/{dataset.replace("-", "_")}/fixed200/er_bal_tabt_seed{seed}/result.json'
                r = read(path)
                assert r['completed']
                rows.append(trajectory(r))
            out.append(('UNSW' if dataset == 'unsw-nb15' else 'CIC') + ' & ' + method.replace('S138-', '').replace('_', r'\_') + ' & ' + ' & '.join(pm([r[i] for r in rows]) for i in range(3)) + r' \\')
    out += [r'\bottomrule\end{tabular}\end{table*}', '']
    return '\n'.join(out)


if __name__ == '__main__':
    target = ROOT / 'paper_aacil/generated/design_space_s138.tex'
    target.write_text(build(), encoding='utf-8', newline='\n')
    print('Validated 192 screening sources; rendered 48 screening and 18 confirmation/comparator rows.')
