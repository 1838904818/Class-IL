"""Render the published design-space evidence without training or re-exporting runs."""
import hashlib
import argparse
import itertools
import json
from pathlib import Path
from statistics import mean, stdev

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / 'paper_aacil/results'


def read(path):
    return json.loads(path.read_text(encoding='utf-8'))


def trajectory(r):
    cps = r['checkpoints']
    tasks = r.get('tasks', r['identity'].get('tasks'))
    recalls = []
    for index, cp in enumerate(cps):
        source = cp if 'operating_points' in cp else r['calibrated_stages'][index]
        assert source['task_index'] == cp['task_index']
        cm = source['operating_points']['0.01']['confusion_matrix']
        recalls.append({c: cm[c][c] / sum(cm[c]) for c in cp['seen_classes']})
    old = [c for task in tasks[:-1] for c in task]
    forgetting = mean(max(x[c] for x in recalls[:-1] if c in x) - recalls[-1][c] for c in old)
    return mean(mean(x.values()) for x in recalls), mean(recalls[-1].values()), forgetting


def pm(values):
    return f'{100*mean(values):.1f} $\\pm$ {100*stdev(values):.1f}'


def paired_evidence(left, right):
    """One-sided superiority, paired by seed; enumerate all sign assignments."""
    from scipy.stats import ttest_rel
    assert len(left) == len(right) == 5
    differences = [a - b for a, b in zip(left, right)]
    observed = mean(differences)
    exact = sum(mean(s*d for s, d in zip(signs, differences)) >= observed - 1e-12
                for signs in itertools.product((-1, 1), repeat=5)) / 32
    return observed, float(ttest_rel(left, right, alternative='greater').pvalue), exact


def build_confirmation():
    """Section 165: reuse completed published cells; never train or re-export."""
    out = [r'% Generated by build_design_space.py --confirmation from published JSON.',
           r'\begin{table*}[t]\centering\scriptsize',
           r'\caption{Confirmation seeds 10--14: mean $\pm$ sample standard deviation. All metrics use the 1\% calibration FPR target (not a guaranteed test FPR). BAcc is macro recall over seen classes; incremental BAcc averages stages. Signed forgetting averages best pre-final minus final recall over old classes, including Normal; negative values are retained. Values are percentages or percentage points.}',
           r'\label{tab:section165-confirmation}',
           r'\begin{tabular}{llrrr}\toprule',
           r'Dataset & Method & Incremental BAcc & Final BAcc & Signed forgetting \\\midrule']
    data = {}
    for dataset, label in [('unsw-nb15', 'UNSW'), ('cic-ids-2017', 'CIC-2017'),
                           ('cse-cic-ids2018', 'CSE-2018')]:
        methods = ['R3-A', 'R3-L', 'ar', 'replay_bs']
        if dataset != 'cse-cic-ids2018':
            methods += ['er_bal_tabt', 'freq', 'wacb']
        data[label] = {}
        for method in methods:
            rows = []
            for seed in range(10, 15):
                if method.startswith('R3-') or dataset == 'cse-cic-ids2018':
                    path = RESULTS / 'section165_confirmation' / dataset / f'{method}_seed{seed}/result.json'
                elif method == 'er_bal_tabt':
                    path = ROOT / f'ncd/results/problem_scout/section123/publication_v1/{dataset.replace("-", "_")}/fixed200/{method}_seed{seed}/result.json'
                else:
                    path = RESULTS / 'section123_confirmation' / dataset / f'{method}_seed{seed}.json'
                result = read(path)
                assert result['completed'], path
                assert result['identity']['seed'] == seed, path
                rows.append(trajectory(result))
            data[label][method] = rows
            out.append(label + ' & ' + method.replace('_', r'\_') + ' & ' +
                       ' & '.join(pm([row[i] for row in rows]) for i in range(3)) + r' \\')
    out += [r'\bottomrule\end{tabular}\end{table*}',
            r'\begin{table*}[t]\centering\scriptsize',
            r'\caption{Paired one-sided t tests and exact sign-flip tests (32 assignments). Differences are first minus second method. R3 tests whether R3-A forgetting is higher than ER; its registered rule requires t p $\geq .05$. Failure to detect harm is not equivalence or non-inferiority. Other criteria require superiority with t p $< .05$. Tests are unadjusted as registered for R1--R5; the separate added-baseline S1 Holm family is not evaluated here.}',
            r'\label{tab:section165-tests}',
            r'\begin{tabular}{llrrr}\toprule',
            r'Dataset & Comparison & Difference (pp) & t p & Sign-flip p \\\midrule']
    for label, methods in data.items():
        comparisons = [('R5a final: R3-A > AR', 'R3-A', 'ar', 1),
                       ('R5b final: R3-A > R3-L', 'R3-A', 'R3-L', 1)] if label == 'CSE-2018' else [
                           ('R1 final: R3-A > ER', 'R3-A', 'er_bal_tabt', 1),
                           ('R2 incremental: R3-A > ER', 'R3-A', 'er_bal_tabt', 0),
                           ('R3 harm: R3-A > ER', 'R3-A', 'er_bal_tabt', 2),
                           ('R4 final: R3-A > R3-L', 'R3-A', 'R3-L', 1)]
        for name, a, b, metric in comparisons:
            delta, t_p, exact = paired_evidence([r[metric] for r in methods[a]],
                                               [r[metric] for r in methods[b]])
            out.append(f'{label} & {name} & {100*delta:.3f} & {t_p:.6g} & {exact:.5f}' + r' \\')
    out += [r'\bottomrule\end{tabular}\end{table*}',
            r'% R3-A has higher forgetting than AR and R3-L on CSE-2018.',
            r'% R5b is narrow under the registered t test; sign-flip p=0.0625.',
            r'% These RQ2 comparisons do not close RQ1, RQ3, or the innovation gate.', '']
    return '\n'.join(out)


def build():
    selection = read(RESULTS / 'section138_selection.json')
    assert len(selection['rows']) == 48
    for name, digest in selection['screening_sha256'].items():
        assert hashlib.sha256((RESULTS / 'section138_screen' / name).read_bytes()).hexdigest() == digest
    out = [r'% Generated by paper_aacil/build_design_space.py from published JSON only.',
           r'\begin{table*}[p]\centering\scriptsize',
           r'\caption{Design-space study; no configuration met the pre-registered K1. Screening seeds 1--2 only. Values are percentages (forgetting in percentage points). Score averages both final decision views over both datasets and seeds. D: default final balanced accuracy; L: final balanced accuracy at a 1\% calibration FPR target; F: signed old-class forgetting in the latter view, including Normal. * denotes selected configurations; R denotes the reference. These screening means are not confirmation evidence.}',
           r'\label{tab:design-space-screen}', r'\begin{tabular}{lrrrrrrr}\toprule',
           r'Configuration & Score & UNSW D & UNSW L & UNSW F & CIC D & CIC L & CIC F \\\midrule']
    for row in selection['rows']:
        name = row['configuration'].replace('S138-', '')
        name += '*' if row['configuration'] in selection['selected'] else (' R' if row['reference'] else '')
        values = [row['score']]
        for dataset in ('UNSW-NB15', 'CIC-IDS-2017'):
            cells = [c for c in row['cells'] if c['dataset'] == dataset]
            assert {c['seed'] for c in cells} == {1, 2}
            values.extend(mean(c[k] for c in cells) for k in ('default_bacc', 'fpr01_bacc', 'forgetting'))
        out.append(name + ' & ' + ' & '.join(f'{100*v:.2f}' for v in values) + r' \\')
    out += [r'\bottomrule\end{tabular}\end{table*}',
            r'\begin{table*}[p]\centering\scriptsize',
            r'\caption{Confirmation-stage descriptive results, seeds 10--14, mean $\pm$ sample standard deviation. All columns use the 1\% calibration FPR target, not default decisions or guaranteed test FPR. All three selected configurations failed K1 on both datasets. K2 passing means no significant worsening under the original test; it does not establish equivalence or non-inferiority. K3 passed under the original criterion. No configuration was confirmed.}',
            r'\label{tab:design-space-confirm}',r'\begin{tabular}{llrrr}\toprule',
            r'Dataset & Configuration & Mean incremental BAcc & Final BAcc & Signed forgetting \\\midrule']
    for dataset in ('unsw-nb15', 'cic-ids-2017'):
        methods = [(m, RESULTS / 'section147_confirmation' / dataset) for m in selection['selected']]
        methods += [(m, RESULTS / 'section123_confirmation' / dataset) for m in ('ar', 'ar_joint', 'replay_bs', 'freq', 'wacb')]
        methods += [('er_bal_tabt', None)]
        for method, directory in methods:
            rows = []
            for seed in range(10, 15):
                path = directory / f'{method}_seed{seed}.json' if directory else ROOT / f'ncd/results/problem_scout/section123/publication_v1/{dataset.replace("-", "_")}/fixed200/er_bal_tabt_seed{seed}/result.json'
                r = read(path)
                assert r['completed']
                rows.append(trajectory(r))
            out.append(('UNSW' if dataset == 'unsw-nb15' else 'CIC') + ' & ' + method.replace('S138-', '').replace('_', r'\_') + ' & ' + ' & '.join(pm([r[i] for r in rows]) for i in range(3)) + r' \\')
    out += [r'\bottomrule\end{tabular}\end{table*}', '']
    return '\n'.join(out)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--confirmation', action='store_true')
    args = parser.parse_args()
    if args.confirmation:
        target = ROOT / 'paper_aacil/generated/section165_confirmation.tex'
        target.write_text(build_confirmation(), encoding='utf-8', newline='\n')
        print('Rendered three-dataset confirmation table from published cells only.')
        raise SystemExit(0)
    target = ROOT / 'paper_aacil/generated/design_space_s138.tex'
    target.write_text(build(), encoding='utf-8', newline='\n')
    print('Validated 192 screening sources; rendered 48 screening and 18 confirmation/comparator rows.')
